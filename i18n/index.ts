const SUPPLEMENTAL_TRANSLATIONS: Record<AppLanguage, TranslationMap> = LANGUAGE_OPTIONS.reduce(
  (accumulator, { code }) => {
    accumulator[code] = {};
    return accumulator;
  },
  {} as Record<AppLanguage, TranslationMap>,
);

Object.entries(SUPPLEMENTAL_TRANSLATIONS_BY_PHRASE).forEach(([phrase, translations]) => {
  Object.entries(translations).forEach(([language, value]) => {
    SUPPLEMENTAL_TRANSLATIONS[language as AppLanguage][phrase] = value;
  });
});

